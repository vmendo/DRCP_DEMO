declare
  procedure add_column_if_missing(p_table varchar2, p_column varchar2, p_definition varchar2) is
    l_count number;
  begin
    select count(*) into l_count
      from user_tab_cols
     where table_name = upper(p_table)
       and column_name = upper(p_column);
    if l_count = 0 then
      execute immediate 'alter table ' || p_table || ' add (' || p_column || ' ' || p_definition || ')';
    end if;
  end;
begin
  add_column_if_missing('drcp_benchmark_runs', 'stop_requested_at', 'timestamp with time zone');
  add_column_if_missing('drcp_benchmark_runs', 'drain_completed_at', 'timestamp with time zone');
  add_column_if_missing('drcp_benchmark_runs', 'save_completed_at', 'timestamp with time zone');
  add_column_if_missing('drcp_benchmark_runs', 'final_reserved_sessions', 'number');
  add_column_if_missing('drcp_benchmark_runs', 'final_active_sessions', 'number');
  add_column_if_missing('drcp_benchmark_runs', 'final_idle_sessions', 'number');
  add_column_if_missing('drcp_benchmark_runs', 'final_resident_servers', 'number');
  add_column_if_missing('drcp_benchmark_runs', 'final_connection_reuse_ratio', 'number');
  add_column_if_missing('drcp_benchmark_runs', 'summary_text', 'varchar2(1000)');
  add_column_if_missing('drcp_benchmark_samples', 'lifecycle_state', 'varchar2(30)');
  add_column_if_missing('drcp_benchmark_samples', 'active_requests', 'number');
  add_column_if_missing('drcp_benchmark_samples', 'in_flight_requests', 'number');
  add_column_if_missing('drcp_benchmark_samples', 'errors', 'number');
  add_column_if_missing('drcp_benchmark_samples', 'current_database_footprint', 'number');

  begin
    execute immediate 'alter table drcp_benchmark_runs drop constraint drcp_benchmark_runs_status_ck';
  exception
    when others then
      if sqlcode != -2443 then
        raise;
      end if;
  end;

  execute immediate q'[
    alter table drcp_benchmark_runs add constraint drcp_benchmark_runs_status_ck
      check (status in ('READY', 'INITIALIZING', 'RUNNING', 'DRAINING', 'SAVING_RESULTS', 'COMPLETED', 'FAILED', 'STOPPED'))
  ]';
end;
/

declare
  l_count number;
begin
  select count(*) into l_count from user_indexes where index_name = 'DRCP_BENCHMARK_RUNS_MODE_IX';
  if l_count = 0 then
    execute immediate 'create index drcp_benchmark_runs_mode_ix on drcp_benchmark_runs (execution_mode, started_at)';
  end if;

  select count(*) into l_count from user_indexes where index_name = 'DRCP_BENCHMARK_RUNS_STARTED_IX';
  if l_count = 0 then
    execute immediate 'create index drcp_benchmark_runs_started_ix on drcp_benchmark_runs (started_at)';
  end if;

  select count(*) into l_count from user_indexes where index_name = 'DRCP_BENCHMARK_SAMPLES_RUN_IX';
  if l_count = 0 then
    execute immediate 'create index drcp_benchmark_samples_run_ix on drcp_benchmark_samples (run_id, sample_ts)';
  end if;
end;
/

